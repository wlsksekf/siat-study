package day03_30;

public class Literal3_escape {
	public static void main(String args[]) {
	    System.out.println("호호하하");
	    System.out.println("\"호호하하\"");
	    System.out.println("호호\n하하\n");
	    System.out.println("호호하하%n");
	    System.out.println("호호\t하하");
	    System.out.println("호호\\하하");
	}
}