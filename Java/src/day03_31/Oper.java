package day03_31;

public class Oper {

	public static void main(String[] args) {
		int a = 10, b = 4, c;
		
		c = a + b;
		System.out.println(a + "+" + b + "=" + c);
		
		c = a - b;
		System.out.println(a + "-" + b + "=" + c);
		
		c = a * b;
		System.out.println(a + "*" + b + "=" + c);
		
		c = a / b;
		System.out.println(a + "/" + b + "=" + c);
		
		c = a % b;
		System.out.println(a + "%" + b + "=" + c);
		
		double a1 = 10, b1 = 4, c1;
		
		c1 = a1 / b1;
		System.out.println(a1 + "/" + b1 + "=" + c1);
	}

}
