# 리스트 안에 튜플
students = [("Kim", 90, 80, 90), ("Lee", 85, 75, 75), ("Park", 95, 90, 90)]

s1 = students[0]
s2 = students[1]
s3 = students[2]

output = (
    f"{'이름'} {'국어'} {'영어'} {'수학'} {'총점'}\n"
    f"{'-' * 55}\f"
    f"{s1[0]} {s1[1]} {s1[2]} {s1[3]} {sum(s1[1:])}점\f"
    f"{s2[0]} {s2[1]} {s2[2]} {s2[3]} {sum(s2[1:])}점\f"
    f"{s3[0]} {s3[1]} {s3[2]} {s3[3]} {sum(s3[1:])}점\n"
    f"{'-' * 55}\f"
    f"{'총점':} {s1[1]+s2[1]+s3[1]} {s1[2]+s2[2]+s3[2]} {s1[3]+s2[3]+s3[3]}"
)

print(output)