# ##### 다형성의 장점
# 1. 유지보수와 확장의 용이성 (Scalability)
# 새로운 결제 수단(예: KakaoPay, ApplePay)이 추가되어도 process_payment 함수를 수정할 필요가 없습니다.
# 기존의 서비스 로직은 그대로 두고, Payment를 상속받는 새로운 클래스만 하나 더 만들면 끝납니다.

# 2. 결합도 낮추기 (Loose Coupling)
# process_payment 함수는 CardPayment나 BankTransferPayment의 내부 동작 방식을 몰라도 됩니다.
# 오직 Payment 인터페이스(추상 클래스)만 알고 있으면 되기 때문에, 특정 기술이나 방식에 종속되지 않습니다.

# 3. 가독성과 표준화
# Payment라는 부모 클래스에서 pay와 cancel 메서드를 강제(@abstractmethod)했기 때문에
# 어떤 개발자가 참여하더라도 동일한 이름의 메서드를 사용하여 코드를 작성하게 됩니다.
# 이는 협업 시 코드의 예측 가능성을 높여줍니다.

# 서비스 로직(Service Logic)
# 서비스 로직(또는 비즈니스 로직)은 애플리케이션이 해결해야 할 핵심 규칙과 절차를 의미합니다.
# 검증(Validation): "결제 금액은 0보다 커야 한다"는 비즈니스 규칙을 검사합니다.
# 워크플로우 제어: "금액이 유효하면 결제를 진행한다"는 실행 순서를 결정합니다.
# 추상적 실행: 구체적으로 카드로 낼지, 계좌이체로 할지는 모르지만 "어쨌든 결제를 처리한다"는 목적 자체를 수행합니다.

# 무엇을(What) 하는가: 결제 금액을 검증하고 결제를 진행합니다. (이것이 서비스 로직입니다.)
# 어떻게(How) 하는가: 카드로 긁을지, 계좌이체를 할지는 서비스 로직의 관심사가 아닙니다.

# ##### 서비스 로직을 분리하는 이유
# 1. 규칙의 집중화: "모든 결제는 0보다 커야 한다"라는 규칙을 한 곳(process_payment)에서만 관리하면 됩니다.
# 2. 가독성, 유지보수성 향상: 비즈니스 규칙이 변경될 때 개별 결제 구현체가 아닌 서비스 로직만 수정하면 됩니다.
# 3. 코드 중복 제거: 결제 수단마다 검증 로직을 중복해서 작성할 필요 없이, 공통된 서비스 로직에서 처리 가능합니다.

# 서비스 로직이란:
# 사용자의 요구사항을 처리하기 위해 데이터를 검증하고, 업무의 순서(프로세서)를 제어하며,
# 비즈니스 규칙을 적용하는 핵심 코드 영역이라고 정의할 수 있습니다.